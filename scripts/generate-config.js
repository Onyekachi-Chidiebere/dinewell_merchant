const fs = require('fs');
const path = require('path');

const release = process.argv.includes('--release');
const DEFAULT_TEST_STRIPE =
  'pk_test_51Qv032FdNOUXRT289ea7PQRfqpSsWt7hyh8XrlUfh1dWAozpzxqJZdyr10fpYPgoJ72sjyGA0NQ79GRpqCfYYzZz00KHWHhrAQ';
const apiUrl = process.env.API_URL || 'https://api.dinewell.ca';
const stripeKey =
  process.env.STRIPE_PUBLISHABLE_KEY || (release ? '' : DEFAULT_TEST_STRIPE);

if (!apiUrl || !/^https:\/\//.test(apiUrl)) {
  throw new Error('API_URL must be an HTTPS URL');
}
if (release) {
  if (!stripeKey || !stripeKey.startsWith('pk_live_')) {
    throw new Error(
      'Release requires STRIPE_PUBLISHABLE_KEY beginning with pk_live_ (set vars.STRIPE_PUBLISHABLE_KEY)',
    );
  }
} else if (!stripeKey || !stripeKey.startsWith('pk_test_')) {
  throw new Error('Development requires a Stripe test publishable key (pk_test_…)');
}

const output = `// Generated by scripts/generate-config.js; never put secret keys here.
export const API_URL = ${JSON.stringify(apiUrl.replace(/\/$/, ''))};
export const STRIPE_PUBLISHABLE_KEY = ${JSON.stringify(stripeKey)};
`;
fs.writeFileSync(path.join(__dirname, '../src/config/generated.ts'), output);
